#!/usr/bin/env python3
"""List framework obligations commencing within N days (regulatory watch)."""
from __future__ import annotations

import argparse
import datetime as dt
import os
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

ap = argparse.ArgumentParser()
ap.add_argument("--days", type=int, default=120)
ap.add_argument("--markdown", type=Path)
ap.add_argument("--today", help="override today's date (YYYY-MM-DD)")
args = ap.parse_args()

today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
horizon = today + dt.timedelta(days=args.days)
doc = yaml.safe_load((ROOT / "catalog/frameworks.yaml").read_text(encoding="utf-8"))

items = []
for f in doc["frameworks"]:
    for kd in f.get("key_dates", []):
        d = dt.date.fromisoformat(str(kd["date"]))
        if today <= d <= horizon:
            items.append((d, f["name"], kd["applies"], f["url"]))
items.sort()

as_of = dt.date.fromisoformat(doc["asOf"])
stale = (today - as_of).days > 90

lines = [f"## AI regulatory obligations commencing by {horizon.isoformat()}", ""]
if items:
    lines += ["| Date | Days | Framework | What applies |", "|---|--:|---|---|"]
    for d, name, applies, url in items:
        lines.append(f"| {d.isoformat()} | {(d - today).days} | [{name}]({url}) | {applies} |")
else:
    lines.append("Nothing commences in this window.")
if stale:
    lines += ["", f"⚠️ The catalogue was last verified on {as_of.isoformat()} ({(today - as_of).days} days ago). Re-verify statuses and update `asOf`."]
lines += ["", "<sub>Generated by the regulatory-watch workflow from catalog/frameworks.yaml.</sub>"]
text = "\n".join(lines) + "\n"
print(text)
if args.markdown:
    args.markdown.write_text(text, encoding="utf-8")
count = len(items) + (1 if stale else 0)
if os.environ.get("GITHUB_OUTPUT"):
    with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as fh:
        fh.write(f"items={count}\n")
