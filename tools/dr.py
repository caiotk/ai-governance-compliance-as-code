#!/usr/bin/env python3
"""Push-button business continuity / disaster recovery for LLM workloads.

Operates on the routing state files the selector produces
(finops/decisions/<workload>.routing.yaml) and regenerates the LiteLLM broker
config so the change is one commit away from the gateway.

  dr.py status   [--workload W]            show active route, RTO/RPO, drill age
  dr.py failover --workload W --to fallback-1 [--reason "..."] [--health-url URL]
  dr.py failback --workload W
  dr.py drill    --workload W [--to fallback-1] [--health-url URL] [--rto-minutes N]
  dr.py report   --workload W              markdown status for the job summary

A failover rewrites `active`, promotes the chosen route to the head of the
LiteLLM fallback chain, records who/when/why, and (optionally) probes the
broker's /health endpoint to time the switch against the RTO. A drill does the
same on a copy, restores the original, and writes a timed drill record — the
evidence APRA CPS 230 para 43, DORA Art 11(6) and ISO 22301 cl. 8.5 ask for.
Nothing here touches cloud control planes: route changes land in the config
the gateway loads; cloud-side failover (APIM priority groups, Bedrock
cross-region profiles) is declared in bcp/terraform and bcp/bicep.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import pathlib
import shutil
import sys
import time
import urllib.error
import urllib.request

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
DECISIONS = ROOT / "finops/decisions"
DRILLS = ROOT / "bcp/drills"
sys.path.insert(0, str(ROOT / "tools"))
import select_model as sm  # noqa: E402


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def load_state(wid: str) -> dict:
    p = DECISIONS / f"{wid}.routing.yaml"
    if not p.exists():
        sys.exit(f"no routing state for {wid}: run tools/select_model.py first")
    return yaml.safe_load(p.read_text())


def save_state(wid: str, st: dict) -> None:
    (DECISIONS / f"{wid}.routing.yaml").write_text(yaml.safe_dump(st, sort_keys=False))


def load_decision(wid: str) -> tuple[dict, dict]:
    d = json.loads((DECISIONS / f"{wid}.decision.json").read_text())
    wl = None
    for p in (ROOT / "finops/examples").glob("*.yaml"):
        w = yaml.safe_load(p.read_text())
        if w.get("metadata", {}).get("id") == wid:
            wl = w
    if wl is None:
        for p in (ROOT / "finops/workloads").glob("*.yaml") if (ROOT / "finops/workloads").exists() else []:
            w = yaml.safe_load(p.read_text())
            if w.get("metadata", {}).get("id") == wid:
                wl = w
    if wl is None:
        sys.exit(f"workload profile for {wid} not found under finops/examples or finops/workloads")
    return d, wl


def regenerate_litellm(wid: str, st: dict) -> pathlib.Path:
    """Rebuild the broker config with the active route first in every fallback chain."""
    d, wl = load_decision(wid)
    cfg = sm.build_litellm(wl, d, d["candidates"])
    active = st["active"]
    if active != "primary":
        route = st["routes"][active]
        primary_group = f"{wid}-primary"
        active_group = f"{wid}-{active}"
        # Point the alias and the primary group at the active deployment: requests for
        # `<wid>` resolve to the active route; the old primary becomes a fallback.
        cfg["router_settings"]["model_group_alias"] = {wid: active_group}
        old_chain = [x for fb in cfg["router_settings"]["fallbacks"] for k, v in fb.items() if k == primary_group for x in v]
        others = [g for g in old_chain if g != active_group]
        # Requests for the primary group go to the active route first; the active
        # route itself falls back to the remaining continuity routes and, last, to
        # the old primary (which may have recovered).
        cfg["router_settings"]["fallbacks"] = (
            [{primary_group: [active_group] + others}, {active_group: others + [primary_group]}]
            + [fb for fb in cfg["router_settings"]["fallbacks"] if primary_group not in fb and active_group not in fb]
        )
        cfg["router_settings"]["default_fallbacks"] = others[:1] or [primary_group]
        # The failed primary trips into cooldown on its first error during the failover.
        for m in cfg["model_list"]:
            if m["model_name"] == primary_group:
                m.setdefault("model_info", {})["allowed_fails"] = 1
                m["model_info"]["cooldown_time"] = 3600
    out = DECISIONS / f"{wid}.litellm.yaml"
    fo = st.get("last_failover") or {}
    header = (f"# Generated by tools/dr.py — active route: {active} ({now()}). See finops/decisions/{wid}.routing.yaml.\n"
              + (f"# FAILOVER ACTIVE since {fo.get('at')} — reason: {fo.get('reason')} — route: {st['routes'][active]['id']}\n" if active != "primary" else ""))
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
    return out


def probe(url: str | None, timeout: float = 10.0) -> dict:
    if not url:
        return {"probed": False}
    t0 = time.time()
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:  # noqa: S310
            body = r.read(4000).decode("utf-8", "replace")
            return {"probed": True, "status": r.status, "ms": int((time.time() - t0) * 1000), "body": body[:500]}
    except urllib.error.HTTPError as e:
        return {"probed": True, "status": e.code, "ms": int((time.time() - t0) * 1000), "error": str(e)}
    except (urllib.error.URLError, OSError, ValueError) as e:
        return {"probed": True, "status": None, "ms": int((time.time() - t0) * 1000), "error": str(e)}


def healthy(h: dict) -> bool:
    """A probe passes only when it ran and returned 200; an unprobed switch is a state change only."""
    return (not h.get("probed")) or h.get("status") == 200


def cmd_status(args) -> int:
    wids = [args.workload] if args.workload else sorted(p.stem.replace(".routing", "") for p in DECISIONS.glob("*.routing.yaml"))
    rows = []
    for wid in wids:
        st = load_state(wid)
        drill = (st.get("last_drill") or {}).get("at")
        age = (dt.datetime.now(dt.timezone.utc) - dt.datetime.fromisoformat(drill)).days if drill else None
        rows.append((wid, st["active"], st["routes"][st["active"]]["id"], st.get("rto_minutes"), drill or "never", age))
    print(f"{'workload':32} {'active':12} {'route':48} {'RTO':>5} {'last drill':26} {'age(d)':>6}")
    for r in rows:
        print(f"{r[0]:32} {r[1]:12} {r[2]:48} {str(r[3] or '-'):>5} {r[4]:26} {str(r[5] if r[5] is not None else '-'):>6}")
    return 0


def switch(wid: str, to: str, reason: str, actor: str, health_url: str | None, kind: str) -> dict:
    st = load_state(wid)
    if to not in st["routes"]:
        sys.exit(f"unknown route {to}; available: {', '.join(st['routes'])}")
    t0 = time.time()
    before = st["active"]
    st["active"] = to
    rec = {"at": now(), "from": before, "to": to, "reason": reason, "actor": actor, "kind": kind}
    st["last_failover" if kind == "failover" else "last_failback"] = rec
    save_state(wid, st)
    cfg_path = regenerate_litellm(wid, st)
    health = probe(health_url)
    rec["switch_seconds"] = round(time.time() - t0, 2)
    rec["health"] = health
    rec["config"] = str(cfg_path.relative_to(ROOT))
    save_state(wid, st)
    return rec


def cmd_failover(args) -> int:
    rec = switch(args.workload, args.to, args.reason, args.actor, args.health_url, "failover")
    print(json.dumps(rec, indent=2))
    return 0 if healthy(rec["health"]) else 1


def cmd_failback(args) -> int:
    rec = switch(args.workload, "primary", args.reason or "failback", args.actor, args.health_url, "failback")
    print(json.dumps(rec, indent=2))
    return 0


def cmd_drill(args) -> int:
    wid = args.workload
    st_path = DECISIONS / f"{wid}.routing.yaml"
    cfg_path = DECISIONS / f"{wid}.litellm.yaml"
    backup_dir = pathlib.Path(os.environ.get("AIGOV_DRILL_TMP", "/tmp")) / f"aigov-drill-{wid}"
    backup_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy(st_path, backup_dir / st_path.name)
    if cfg_path.exists():
        shutil.copy(cfg_path, backup_dir / cfg_path.name)
    st = load_state(wid)
    target = args.to or next((k for k in st["routes"] if k != "primary"), None)
    if not target:
        sys.exit("no fallback route to drill — the selector found no second vendor/platform (see min_vendors_for_resilience)")
    rto = args.rto_minutes or st.get("rto_minutes") or 30
    t0 = time.time()
    steps = []
    try:
        rec = switch(wid, target, f"DR drill (scenario: {args.scenario})", args.actor, args.health_url, "failover")
        steps.append({"step": "failover", **rec})
        back = switch(wid, "primary", "drill failback", args.actor, args.health_url, "failback")
        steps.append({"step": "failback", **back})
    finally:
        # Restore pre-drill files so the drill leaves no production change behind, even on error.
        shutil.copy(backup_dir / st_path.name, st_path)
        if (backup_dir / cfg_path.name).exists():
            shutil.copy(backup_dir / cfg_path.name, cfg_path)
    elapsed = time.time() - t0
    st = load_state(wid)
    probed = any(s.get("health", {}).get("probed") for s in steps)
    ok = all(healthy(s.get("health", {})) for s in steps)
    within_rto = elapsed <= rto * 60
    result = "pass" if (ok and within_rto) else "fail"
    drill = {"at": now(), "scenario": args.scenario, "target": target, "actor": args.actor, "elapsed_seconds": round(elapsed, 2),
             "rto_minutes": rto, "within_rto": within_rto, "health_ok": ok, "gateway_probed": probed,
             "evidence_scope": "state change timed against the gateway health endpoint" if probed else "state change only — no gateway probe (pass --health-url for continuity evidence)",
             "result": result, "steps": steps}
    st["last_drill"] = {k: drill[k] for k in ("at", "scenario", "target", "result", "elapsed_seconds", "rto_minutes")}
    st["rto_minutes"] = rto
    save_state(wid, st)
    DRILLS.mkdir(parents=True, exist_ok=True)
    out = DRILLS / f"{wid}-{drill['at'].replace(':', '').replace('+0000', 'Z')}.json"
    out.write_text(json.dumps(drill, indent=2) + "\n")
    print(json.dumps({k: v for k, v in drill.items() if k != "steps"}, indent=2))
    print(f"drill record: {out.relative_to(ROOT)}")
    return 0 if drill["result"] == "pass" else 1


def cmd_report(args) -> int:
    st = load_state(args.workload)
    a = st["active"]
    lines = [f"## BCP/DR — `{args.workload}`", "", f"- **Active route:** `{a}` → `{st['routes'][a]['id']}`",
             f"- **Mode:** {st['mode']} · expected ${st.get('expected_monthly_usd') or 0:,.2f}/month (budget ${st.get('budget_monthly_usd') or 0:,.2f})",
             f"- **RTO:** {st.get('rto_minutes') or '-'} min · **last drill:** {(st.get('last_drill') or {}).get('at', 'never')} ({(st.get('last_drill') or {}).get('result', '-')})",
             f"- **Last failover:** {(st.get('last_failover') or {}).get('at', 'none')} {(st.get('last_failover') or {}).get('reason', '')}", "",
             "| Route | Model | Platform | Reason |", "|---|---|---|---|"]
    for k, r in st["routes"].items():
        lines.append(f"| {'**' + k + '**' if k == a else k} | `{r['id']}` | {r['platform']} | {r.get('reason', 'primary')} |")
    print("\n".join(lines))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("status"); s.add_argument("--workload"); s.set_defaults(fn=cmd_status)
    for name, fn in (("failover", cmd_failover), ("failback", cmd_failback)):
        s = sub.add_parser(name); s.add_argument("--workload", required=True); s.add_argument("--to", default="fallback-1")
        s.add_argument("--reason", default=""); s.add_argument("--actor", default=os.environ.get("GITHUB_ACTOR", os.environ.get("USER", "unknown")))
        s.add_argument("--health-url"); s.set_defaults(fn=fn)
    s = sub.add_parser("drill"); s.add_argument("--workload", required=True); s.add_argument("--to"); s.add_argument("--scenario", default="primary vendor outage")
    s.add_argument("--rto-minutes", type=int); s.add_argument("--health-url"); s.add_argument("--actor", default=os.environ.get("GITHUB_ACTOR", "drill-bot")); s.set_defaults(fn=cmd_drill)
    s = sub.add_parser("report"); s.add_argument("--workload", required=True); s.set_defaults(fn=cmd_report)
    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
